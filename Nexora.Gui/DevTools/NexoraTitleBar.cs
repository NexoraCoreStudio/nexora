using Avalonia;
using Avalonia.Controls;
using Avalonia.Input;
using Avalonia.Layout;
using Avalonia.Controls.ApplicationLifetimes;
using Nexora.Gui.Dialogs;
using Avalonia.Media;
using Nexora.Gui.Updates;
using Nexora.Gui.Settings;
using Nexora.Gui.Services;

namespace Nexora.Gui.DevTools;

/// <summary>A compact custom window title bar with native-like window controls and an update action.</summary>
internal static class NexoraTitleBar
{
    public static void Attach(MainWindow window, UpdateCoordinator updater, IStickManager sticks)
    {
        if (window.Content is not Control original) return;
        AddDisconnectButton(original, window);
        // Our own decoration permits the Update button beside minimize / maximize / close.
        window.SystemDecorations = SystemDecorations.None;
        var bar = new Grid
        {
            Height = 43,
            ColumnDefinitions = new ColumnDefinitions("*,Auto,Auto,Auto,Auto,Auto"),
            Background = Brush.Parse("#111B30")
        };
        var drag = new Border { Background = Brushes.Transparent, Padding = new Thickness(16, 10) };
        drag.Child = new TextBlock
        {
            Text = "NEXORA  ·  VIRTUAL SECURITY KEY  ·  v" + DisplayVersion + (DevEnabled ? "  [DEV]" : ""),
            FontWeight = FontWeight.SemiBold,
            FontSize = 12,
            Foreground = Brush.Parse("#C3CFFC"),
            VerticalAlignment = VerticalAlignment.Center
        };
        drag.PointerPressed += (_, e) =>
        {
            if (e.GetCurrentPoint(window).Properties.IsLeftButtonPressed) window.BeginMoveDrag(e);
        };
        drag.DoubleTapped += (_, _) => ToggleMaximize(window);
        bar.Children.Add(drag);
        var update = MakeButton("↻  Vérifier", "#23384F", 125);
        update.Click += async (_, _) => await updater.OpenUpdateCenterAsync();
        Grid.SetColumn(update, 1); bar.Children.Add(update);
        updater.AvailabilityChanged += available =>
        {
            update.Content = available ? "⬇  UPDATE" : "↻  Vérifier";
            update.Background = Brush.Parse(available ? "#136C61" : "#23384F");
        };
        var settings = MakeButton("⚙  Paramètres", "#293550", 117);
        settings.Click += async (_, _) => await SettingsWindow.ShowAsync(window, updater, sticks);
        Grid.SetColumn(settings, 2); bar.Children.Add(settings);
        var minimize = MakeButton("—", "#17263B", 40);
        minimize.Click += (_, _) => window.WindowState = WindowState.Minimized;
        Grid.SetColumn(minimize, 3); bar.Children.Add(minimize);
        var maximize = MakeButton("□", "#17263B", 40);
        maximize.Click += (_, _) => ToggleMaximize(window);
        Grid.SetColumn(maximize, 4); bar.Children.Add(maximize);
        var close = MakeButton("✕", "#66252F", 43);
        close.Click += (_, _) => window.Close(); // Existing close handler locks the vault.
        Grid.SetColumn(close, 5); bar.Children.Add(close);
        var layout = new Grid { RowDefinitions = new RowDefinitions("Auto,*") };
        // Detach first: Avalonia does not permit a control to have two visual parents.
        window.Content = null;
        layout.Children.Add(bar);
        Grid.SetRow(original, 1);
        layout.Children.Add(original);
        window.Content = layout;
    }

#if NEXORA_DEV
    private const bool DevEnabled = true;
#else
    private const bool DevEnabled = false;
#endif

    // Always comes from the assembly generated by Nexora.Gui.csproj (<Version>).
    // No hard-coded version: remains correct after a future release.
    internal static string DisplayVersion
    {
        get
        {
            var v = typeof(App).Assembly.GetName().Version;
            return v is null ? "inconnue" : $"{v.Major}.{v.Minor}.{Math.Max(0, v.Build)}";
        }
    }

    // The existing dashboard is loaded from XAML. Put the exit action immediately after
    // the 'Verrouiller' action, without changing the lock behavior or tray controls.
    private static void AddDisconnectButton(Control original, MainWindow window)
    {
        var button = new Button
        {
            Content = "⏻  Déconnexion",
            HorizontalAlignment = HorizontalAlignment.Stretch,
            Margin = new Thickness(0, 2, 0, 0),
            Background = Brush.Parse("#632D3B"),
            Foreground = Brushes.White
        };
        button.Click += async (_, _) =>
        {
            button.IsEnabled = false;
            try
            {
                // First detach USB/IP and lock the vault; then terminate the desktop lifetime.
                await window.ForceCloseAsync();
                if (Application.Current?.ApplicationLifetime is IClassicDesktopStyleApplicationLifetime desktop)
                    desktop.Shutdown();
            }
            catch (Exception ex)
            {
                button.IsEnabled = true;
                await MessageWindow.ShowAsync(window, "Déconnexion impossible", ex.Message);
            }
        };

        if (!InsertAfterLock(original, button))
            DevConsole.Write("WARN", "disconnect-button-not-found");
    }

    private static bool InsertAfterLock(Control parent, Button exitButton)
    {
        if (parent is StackPanel stack)
        {
            for (int i = 0; i < stack.Children.Count; i++)
            {
                if (stack.Children[i] is Button b && b.Content is string caption
                    && caption.Contains("Verrouiller", StringComparison.OrdinalIgnoreCase))
                {
                    stack.Children.Insert(i + 1, exitButton);
                    return true;
                }
            }
        }
        if (parent is Panel panel)
        {
            foreach (var child in panel.Children)
                if (InsertAfterLock(child, exitButton)) return true;
        }
        else if (parent is Decorator decorator && decorator.Child is Control child)
        {
            if (InsertAfterLock(child, exitButton)) return true;
        }
        else if (parent is ContentControl content && content.Content is Control control)
        {
            if (InsertAfterLock(control, exitButton)) return true;
        }
        return false;
    }

    private static Button MakeButton(string text, string background, double width) => new()
    {
        Content = text,
        Width = width,
        Height = 36,
        Margin = new Thickness(2, 3),
        FontSize = 12,
        Background = Brush.Parse(background),
        Foreground = Brushes.White,
        Padding = new Thickness(7, 5)
    };

    private static void ToggleMaximize(Window window) => window.WindowState =
        window.WindowState == WindowState.Maximized ? WindowState.Normal : WindowState.Maximized;
}
